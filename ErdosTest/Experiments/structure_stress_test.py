#!/usr/bin/env python3
"""
Phase 10 — Structural Stress Testing.

For each candidate structure from Phase 9:
  (1) divisorResidueSet  R(M,a) = { d mod a : d | M^2 }
  (2) AstratumSolvable
  (3) bounded-exponent product set  R(M,a) = { prod p_i^{f_i} : 0 <= f_i <= 2 v_i(M) }

we run necessity / sufficiency / counterexample / simplification probes.

All output is register B (finite computation, no proof).  The point is NOT to solve the
conjecture; it is to decide whether each structure carries genuine leverage.
"""

from itertools import product
from sympy import isprime, factorint
from math import gcd


def divisors_of_square(M):
    """All divisors of M^2 as a set (bounded exponents 0..2e_i)."""
    fac = factorint(M)
    ps = list(fac)
    es = list(fac.values())
    out = set()
    for combo in product(*(range(2 * e + 1) for e in es)):
        d = 1
        for pi, ei in zip(ps, combo):
            d *= pi ** ei
        out.add(d)
    return out


def residue_set(M, a):
    return {d % a for d in divisors_of_square(M)}


def subgroup_generated(M, a):
    """The subgroup of (Z/a)^* generated by the residues of the prime factors of M."""
    gens = {p % a for p in factorint(M)}
    S = {1 % a}
    changed = True
    while changed:
        changed = False
        for s in list(S):
            for g in gens:
                t = (s * g) % a
                if t not in S:
                    S.add(t)
                    changed = True
    return S


def one_sided_ok(M, a):
    return any((d + M) % a == 0 for d in divisors_of_square(M))


def two_sided_ok(M, a):
    M2 = M * M
    return any((d + M) % a == 0 and (M2 // d + M) % a == 0 for d in divisors_of_square(M))


def a_works(p, a):
    """Full two-sided certificate for stratum a (M = p(p+a)/4)."""
    if (p + a) % 4 != 0:
        return False
    M = p * (p + a) // 4
    return two_sided_ok(M, a)


def main():
    print("=" * 70)
    print("1. ONE-SIDED CRITERION: is gcd(M,a)=1 NECESSARY?")
    print("=" * 70)
    # Find smallest (M,a) with gcd != 1 where one-sided holds but two-sided fails.
    counter = []
    for M in range(1, 40):
        for a in range(2, 40):
            if gcd(M, a) == 1:
                continue
            if one_sided_ok(M, a) and not two_sided_ok(M, a):
                counter.append((M, a))
    print(f"  counterexamples (gcd!=1, one-sided holds but two-sided fails): "
          f"{counter[:10]}")
    if counter:
        M, a = counter[0]
        M2 = M * M
        bad = [(d, M2 // d) for d in divisors_of_square(M)
               if (d + M) % a == 0 and (M2 // d + M) % a != 0]
        print(f"  smallest: M={M}, a={a}, gcd={gcd(M,a)}, "
              f"witness d, M^2/d = {bad[0] if bad else None}")
    # And the flip side: gcd=1 -> no counterexample (corroborates the Lean theorem)
    n_gcd1 = 0
    for M in range(1, 60):
        for a in range(2, 60):
            if gcd(M, a) == 1 and one_sided_ok(M, a) != two_sided_ok(M, a):
                n_gcd1 += 1
    print(f"  (corroboration) gcd=1 mismatches for M,a<60: {n_gcd1}  (expect 0)")

    print()
    print("=" * 70)
    print("2. R(M,a) vs generated SUBGROUP (bounded exponent != subgroup)")
    print("=" * 70)
    for (M, a) in [(2, 5), (3, 7), (5, 7), (2, 7), (6, 11)]:
        R = residue_set(M, a)
        G = subgroup_generated(M, a)
        print(f"  M={M}, a={a}: R(M,a)={sorted(R)}  <p_i> subgroup={sorted(G)}  "
              f"equal={R == G}  subgroup\\R={sorted(G - R)}")

    print()
    print("=" * 70)
    print("3. MINIMAL-a GROWTH (AstratumSolvable: is the invariant informative?)")
    print("=" * 70)
    N = 100000
    primes = [p for p in range(5, N + 1, 4) if isprime(p)]
    records = []           # (p, minimal a) when minimal a strictly grows
    cur_max = 0
    no_solution = []
    for p in primes:
        amin = None
        for a in range(3, 120, 4):
            if a_works(p, a):
                amin = a
                break
        if amin is None:
            no_solution.append(p)
        else:
            if amin > cur_max:
                records.append((p, amin))
                cur_max = amin
    print(f"  primes p≡1(4) <= {N}: {len(primes)}, none with minimal a >= 120 "
          f"up to 120: {len(no_solution)}")
    print(f"  record (p, minimal a) sequence:")
    for p, a in records:
        print(f"    p={p:>6}  ->  minimal a = {a}")

    print()
    print("=" * 70)
    print("4. conjecture holds in range (no counterexample found) — honest note")
    print("=" * 70)
    print(f"  every prime p≡1(4) <= {N} has SOME stratum a <= 119: "
          f"{len(no_solution) == 0}  (already known to far larger ranges)")

    print()
    print("NOTE: register B only — finite computation, no proof.")


if __name__ == "__main__":
    main()
