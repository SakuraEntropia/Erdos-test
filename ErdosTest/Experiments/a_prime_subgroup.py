#!/usr/bin/env python3
"""
Characterize a=q (q prime) via the divisor-residue structure of M = p(p+q)/4.

CORRECTED result (register B): the certificate collapses to ONE residue condition.

  For n = 1 (mod 4), a = 3 (mod 4), a > 0, and M = n(n+a)/4:
      "a works"  <=>  M^2 has a divisor d with  d == -M  (mod a).
  (The second certificate condition  a | M^2/d + M  is automatic.)

This is verified below against the FULL two-sided certificate (d,e with a|d+M, a|e+M, d*e=M^2),
for prime a = q and for composite a.  We then spell out:

  * the TARGET COSET LAW: for prime a=q,  -M = -n^2 * 4^{-1} (mod q), so -M always lies in
    the coset (-4^{-1}) * (quadratic residues).  For q = 3 (mod 4) that coset is exactly the
    NON-RESIDUES:  q=7 -> {3,5,6};  q=11 -> {2,6,7,8,10}.

  * the CLEAN criterion for a=7:  a=7 works  <=>  D(x^2) meets {5 n^2, 5 n, 5} (mod 7),
    where x=(n+7)/4 and D(x^2) is the set of residues mod 7 of divisors of x^2 (exponents 0..2e_i).
    In particular a=7 works for ALL n = 3, 6 (mod 7).

NOTE: an earlier guess (residues of divisors of M^2 form the subgroup generated by prime factors)
is FALSE -- exponents are bounded (0..2 e_i), so the attainable set is a bounded product set, not
the full subgroup.  This script uses the correct bounded-exponent set throughout.

All output register B (finite computation, no proof).
"""

from itertools import product
from sympy import isprime, factorint


def a_works(p, a):
    """Full two-sided certificate: a | d+M and a | M^2/d + M for some d | M^2."""
    if (p + a) % 4 != 0:
        return False
    x = (p + a) // 4
    M = p * x
    fac = factorint(M)
    ps = list(fac)
    es = list(fac.values())
    M2 = M * M
    for combo in product(*(range(2 * e + 1) for e in es)):
        d = 1
        for pi, ei in zip(ps, combo):
            d *= pi ** ei
        if (d + M) % a == 0 and (M2 // d + M) % a == 0:
            return True
    return False


def one_sided(p, a):
    """One-sided criterion: exists d | M^2 with d == -M (mod a)."""
    if (p + a) % 4 != 0:
        return False
    x = (p + a) // 4
    M = p * x
    fac = factorint(M)
    ps = list(fac)
    es = list(fac.values())
    for combo in product(*(range(2 * e + 1) for e in es)):
        d = 1
        for pi, ei in zip(ps, combo):
            d *= pi ** ei
        if (d + M) % a == 0:
            return True
    return False


def residue_set_of_square(m, q):
    """Residues mod q attained by divisors of m^2 (bounded exponents 0..2e_i)."""
    S = {1}
    for pi, e in factorint(m).items():
        r = pi % q
        powers = set()
        v = 1
        for _ in range(2 * e + 1):
            powers.add(v)
            v = (v * r) % q
        S = { (s * pw) % q for s in S for pw in powers }
    return S


def a7_clean(p):
    """a=7 works  <=>  D(x^2) meets {5 p^2, 5 p, 5} (mod 7), x=(p+7)/4."""
    x = (p + 7) // 4
    D = residue_set_of_square(x, 7)
    targets = {(5 * p * p) % 7, (5 * p) % 7, 5}
    return bool(D & targets)


def main():
    N = 40000
    primes = [p for p in range(5, N + 1, 4) if isprime(p)]

    print("=== 1. one-sided criterion vs full certificate (should be 0 mismatches) ===\n")
    for a in [3, 7, 11, 19, 23, 31, 43, 15, 21, 27, 35, 39, 45, 55, 63, 91, 119]:
        mm = 0
        for p in primes:
            if p == a:
                continue
            if a_works(p, a) != one_sided(p, a):
                mm += 1
        print(f"  a={a:>3}: mismatches={mm}")

    print("\n=== 2. target coset law: -M mod q for prime q ===\n")
    for q in [7, 11]:
        seen = set()
        for p in primes:
            if p == q:
                continue
            x = (p + q) // 4
            M = p * x
            seen.add((-M) % q)
        print(f"  q={q}: attainable -M mod q = {sorted(seen)}")

    print("\n=== 3. clean a=7 criterion vs full certificate (should be 0) ===\n")
    mm = 0
    for p in primes:
        if p == 7:
            continue
        if a7_clean(p) != a_works(p, 7):
            mm += 1
    print(f"  a=7 clean: primes={len([p for p in primes if p!=7])}, mismatches={mm}")

    print("\nNOTE: register B only -- finite computation, no proof.")


if __name__ == "__main__":
    main()
